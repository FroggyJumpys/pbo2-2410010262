        perbaruiRingkasan();

        tambahButton.addActionListener(e -> tambah());
        bersihkanButton.addActionListener(e -> bersihkan());
        // Enter di field mana pun sama dengan menekan Tambah
        getRootPane().setDefaultButton(tambahButton);

